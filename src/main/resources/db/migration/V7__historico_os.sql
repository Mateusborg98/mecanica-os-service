CREATE TABLE historico_os (
    sequencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id UUID NOT NULL REFERENCES ordem_de_servico_jpa_entity(id),
    tipo VARCHAR(40) NOT NULL,
    event_id UUID NOT NULL,
    origem VARCHAR(32) NOT NULL,
    status_anterior VARCHAR(32),
    status_atual VARCHAR(32) NOT NULL,
    ocorrido_em TIMESTAMP WITH TIME ZONE,
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(ordem_id,tipo,event_id)
);
CREATE INDEX idx_historico_os_cursor ON historico_os(ordem_id,sequencia);
